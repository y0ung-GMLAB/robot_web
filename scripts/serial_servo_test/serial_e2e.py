def state(link):
    try:
        with open(link + '.state') as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def ctl(link, cmd):
    with open(link + '.ctl', 'a') as f:
        f.write(cmd + '\n')


class Client(Node):
    def __init__(self):
        super().__init__('serial_e2e_client')
        qos = QoSProfile(depth=1, reliability=ReliabilityPolicy.BEST_EFFORT)
        self.last = None
        self.create_subscription(MotorStatus, 'motion_control/motor_status', self.on_status, qos)
        self.cmd = self.create_publisher(MotorStatus, 'motion_control/motor_command', qos)

    def on_status(self, msg):
        self.last = msg

    def spin_for(self, sec):
        end = time.time() + sec
        while time.time() < end:
            rclpy.spin_once(self, timeout_sec=0.01)

    def wait(self, pred, sec):
        end = time.time() + sec
        while time.time() < end:
            rclpy.spin_once(self, timeout_sec=0.01)
            try:
                if self.last is not None and pred(self.last):
                    return True
            except (TypeError, KeyError):
                pass  # an axis not reported yet
        return False

    def send(self, index, interfaces, controlword=0, position=0.0):
        msg = MotorStatus()
        msg.number_of_target_interfaces = [len(interfaces)]
        ids = Int8MultiArray()
        ids.data = list(interfaces)
        msg.target_interface_id = [ids]
        msg.controller_index = [index]
        msg.controlword = [controlword]
        msg.statusword = [0]
        msg.errorcode = [0]
        msg.position = [position]
        msg.velocity = [0.0]
        msg.effort = [0.0]
        for _ in range(5):
            self.cmd.publish(msg)
            self.spin_for(0.02)


def row(msg, index):
    for k, ci in enumerate(msg.controller_index):
        if ci == index:
            return {'err': msg.errorcode[k], 'sw': msg.statusword[k], 'pos': msg.position[k]}
    return None


def start_node(log_name):
    log = open(f'{WORK}/{log_name}.log', 'w')
    exe = subprocess.check_output(['ros2', 'pkg', 'prefix', 'motion_control_bridge'], text=True).strip()
    return subprocess.Popen(
        [exe + '/lib/motion_control_bridge/motor_manager_node', '--ros-args',
         '-p', f'config_file:={WORK}/motor_config.yaml'],
        stdout=log, stderr=subprocess.STDOUT)


def stop(proc):
    proc.send_signal(2)  # SIGINT · rclcpp shutdown
    try:
        proc.wait(5)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(5)
    check('node stopped', proc.poll() is not None, f'exit {proc.returncode}')


def main():
    write_configs()
    for link in (DXL, FT):
        for suffix in ('', '.state', '.ctl'):
            if os.path.lexists(link + suffix):
                os.remove(link + suffix)
    fakes = [
        subprocess.Popen([sys.executable, HERE + '/fake_servo_bus.py', 'dxl2', DXL, '1,2']),
        subprocess.Popen([sys.executable, HERE + '/fake_servo_bus.py', 'scs', FT, '1']),
    ]
    time.sleep(0.5)
    rclpy.init()
    client = Client()
    node = start_node('run1')
    try:
        # --- A. start · items · auto torque on · positions ---
        ok = client.wait(lambda m: len(m.controller_index) == 3 and all(
            (row(m, i) or {}).get('sw') == 1 and (row(m, i) or {}).get('err') == 0 for i in range(3)), 8)
        check('A1 3 axes up, torque on, no error', ok, str(client.last and [row(client.last, i) for i in range(3)]))
        d = state(DXL)
        f = state(FT)
        if not (d and all(s['mode'] == 4 for s in d['servos'].values())):
            print('STATE dxl', json.dumps(d)[:1500])
            print('STATE ft', json.dumps(f)[:800])
        check('A2 DXL Operating Mode written 4 (was 3)', d and all(s['mode'] == 4 for s in d['servos'].values()),
              str(d and [s['mode'] for s in d['servos'].values()]))
        f = state(FT)
        ft_acc = [w for w in f['servos']['1']['writes'] if w[0] == 41] if f else []
        ft_vel = [w for w in f['servos']['1']['writes'] if w[0] == 46] if f else []
        check('A3 FT Acceleration item = 879/8.789 = 100', ft_acc and ft_acc[-1][1] == [100], str(ft_acc))
        check('A4 FT Goal Velocity item = 360 deg/s = 4096 step/s', ft_vel and ft_vel[-1][1] == list((4096).to_bytes(2, 'little')), str(ft_vel))
        m = client.last
        exp_dxl = 100 * 2 * math.pi / 4095
        exp_ft = 100 * 2 * math.pi / 4096
        check('A5 DXL id1 position 2148 raw', abs(row(m, 0)['pos'] - exp_dxl) < 1e-4, f"{row(m, 0)['pos']:.5f} vs {exp_dxl:.5f}")
        check('A6 FT id1 position 2148 raw', abs(row(m, 2)['pos'] - exp_ft) < 1e-4, f"{row(m, 2)['pos']:.5f} vs {exp_ft:.5f}")

        # --- B. commands ---
        client.send(0, [1], position=0.5)
        client.send(2, [1], position=-0.5)
        client.spin_for(0.3)
        d, f = state(DXL), state(FT)
        dxl_goal = int.from_bytes(bytes(d['servos']['1']['goal']), 'little', signed=True)
        ft_goal = int.from_bytes(bytes(f['servos']['1']['goal']), 'little')
        exp_g_dxl = round(2048 + 0.5 / (2 * math.pi / 4095))
        exp_g_ft = round(2048 - 0.5 / (2 * math.pi / 4096))
        check('B1 DXL goal raw', dxl_goal == exp_g_dxl, f'{dxl_goal} vs {exp_g_dxl}')
        check('B2 FT goal raw', ft_goal == exp_g_ft, f'{ft_goal} vs {exp_g_ft}')
        client.wait(lambda mm: abs(row(mm, 2)['pos'] + 0.5) < 2e-3, 2)
        check('B3 FT present follows goal', abs(row(client.last, 2)['pos'] + 0.5) < 2e-3, f"{row(client.last, 2)['pos']:.4f}")
        # sign-magnitude decode · present raw −100 (bit 15 set)
        ctl(FT, 'move 1 -100')
        exp_neg = (-100 - 2048) * 2 * math.pi / 4096
        ok = client.wait(lambda mm: abs(row(mm, 2)['pos'] - exp_neg) < 1e-3, 2)
        check('B4 FT negative (sign bit 15) decode', ok, f"{row(client.last, 2)['pos']:.4f} vs {exp_neg:.4f}")
        # sign-magnitude encode · a goal below raw 0 is written as bit 15 + magnitude
        client.send(2, [1], position=-3.3)
        client.spin_for(0.3)
        f = state(FT)
        raw = int.from_bytes(bytes(f['servos']['1']['goal']), 'little')
        exp_mag = round(2048 - 3.3 / (2 * math.pi / 4096))
        if FT_RAW_MIN < 0:
            check('B5 FT negative goal encoded sign-magnitude', raw == (0x8000 | -exp_mag) if exp_mag < 0 else False, f'0x{raw:04x} exp mag {exp_mag}')
        else:
            check('B5 FT goal below one turn clamped to raw 0 (position_raw_min)', raw == 0, f'0x{raw:04x}')

        # --- C. forbidden values ---
        client.send(1, [0], controlword=0x0F)
        client.spin_for(0.3)
        d = state(DXL)
        bad = [w for w in d['servos']['2']['writes'] if w[0] == 64 and w[1] != [0] and w[1] != [1]]
        check('C1 DXL controlword 15 never written', not bad and d['servos']['2']['torque'] == 1, str(bad))
        client.send(2, [0], controlword=0x80)
        client.spin_for(0.5)
        f = state(FT)
        check('C2 FT alarm reset → torque 0, no 128, no RESET', f['servos']['1']['torque'] == 0 and not f['servos']['1']['forbidden'],
              f"torque {f['servos']['1']['torque']} forbidden {f['servos']['1']['forbidden']}")
        client.send(2, [0], controlword=1)
        ok = client.wait(lambda mm: row(mm, 2)['sw'] == 1, 2)
        check('C3 FT torque back on with controlword 1', ok)

        # --- D. unplug DXL · Feetech keeps running ---
        ctl(DXL, 'unplug')
        ok = client.wait(lambda mm: row(mm, 0)['err'] == 0xFFFF and row(mm, 1)['err'] == 0xFFFF, 4)
        check('D1 DXL axes 0xFFFF after unplug', ok, str([row(client.last, i) for i in range(3)]))
        client.send(2, [1], position=0.2)
        ok = client.wait(lambda mm: abs(row(mm, 2)['pos'] - 0.2) < 2e-3 and row(mm, 2)['err'] == 0, 2)
        check('D2 FT still commanded and read while DXL is gone', ok, str(row(client.last, 2)))
        check('D3 node still alive', node.poll() is None)
        ctl(DXL, 'plug')
        ok = client.wait(lambda mm: row(mm, 0)['err'] == 0 and row(mm, 1)['err'] == 0, 6)
        check('D4 DXL back after replug', ok, str([row(client.last, i) for i in range(3)]))
        client.send(0, [1], position=-0.25)
        client.spin_for(0.4)
        d = state(DXL)
        g = int.from_bytes(bytes(d['servos']['1']['goal']), 'little', signed=True)
        check('D5 DXL takes commands after replug', g == round(2048 - 0.25 / (2 * math.pi / 4095)), str(g))
    finally:
        stop(node)

    # --- E. start with the DXL port missing ---
    ctl(DXL, 'unplug')
    time.sleep(0.5)
    check('E0 DXL link removed before start', not os.path.lexists(DXL))
    client.spin_for(0.5)
    client.last = None
    node = start_node('run2')
    try:
        ok = client.wait(lambda mm: len(mm.controller_index) == 3 and row(mm, 2)['err'] == 0 and row(mm, 2)['sw'] == 1
                         and row(mm, 0)['err'] == 0xFFFF, 8)
        check('E1 node starts, Feetech runs with DXL port missing', ok and node.poll() is None,
              str(client.last and [row(client.last, i) for i in range(3)]))
        check('E2 DXL axes report 0xFFFF', client.last and row(client.last, 0)['err'] == 0xFFFF, str(client.last and row(client.last, 0)))
        ctl(DXL, 'plug')
        ok = client.wait(lambda mm: row(mm, 0)['err'] == 0 and row(mm, 0)['sw'] == 1 and row(mm, 1)['sw'] == 1, 8)
        check('E3 DXL comes up after plug (items + torque)', ok, str([row(client.last, i) for i in range(3)]))
    finally:
        stop(node)
        client.destroy_node()
        rclpy.shutdown()
        for p in fakes:
            p.terminate()

    failed = [r for r in RESULTS if not r[1]]
    print(f'\n{len(RESULTS) - len(failed)}/{len(RESULTS)} passed', flush=True)
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
